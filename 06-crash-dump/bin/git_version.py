Import("env")

import os
from subprocess import check_output, DEVNULL
from datetime import datetime


def git(cmd):
    try:
        out = check_output("git " + cmd, shell=True, stderr=DEVNULL,
                           cwd=env.subst("$PROJECT_DIR"))
        return out.decode().strip()
    except Exception:
        return "unknown"


version = git("describe --tags --always --dirty")
sha = git("rev-parse --short HEAD")
build_time = datetime.now().strftime("%Y-%m-%d %H:%M:%S")
build_env = env["PIOENV"]

header = f"""// Generated by bin/git_version.py -- do not edit, do not commit
#pragma once

#define FW_VERSION "{version}"
#define GIT_HASH   "{sha}"
#define BUILD_TIME "{build_time}"
#define BUILD_ENV  "{build_env}"
"""

path = os.path.join(env.subst("$PROJECT_INCLUDE_DIR"), "version.h")

# Rewrite only when content changed, so unchanged builds stay incremental
old = None
if os.path.exists(path):
    with open(path) as f:
        old = f.read()

if old != header:
    with open(path, "w") as f:
        f.write(header)
